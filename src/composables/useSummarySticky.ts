import { computed, ref } from 'vue'

/**
 * Прилипшая шапка сводки заказа.
 *
 * Итоговая сумма лежит в самом низу страницы, под адресом, доставкой и
 * оплатой. Человек, который держит её в голове («хватит ли кошелька»,
 * «сколько с доставкой»), вынужден листать туда и обратно, теряя место, на
 * котором остановился. Поэтому шапка сводки прилипает к верху экрана и
 * несёт сумму с собой, а по нажатию раскрывается в полную сводку.
 *
 * Отлипает она, когда блок сводки внизу страницы виден на треть и больше.
 * Там сумма уже читается в самом блоке, и держать её ещё и наверху значит
 * показывать два «Итого» сразу.
 *
 * Порог искали дважды. Сперва было «как только блок показался на экране» —
 * на коротких страницах полоса не прилипала вовсе: у модального концепта
 * тело чекаута умещается почти целиком, сводка видна снизу сразу, и полоса
 * отпускалась на первом же движении. Потом «пока блок не доехал до самой
 * полосы» — другая крайность: блок уже стоял посреди экрана со своей
 * суммой, а полоса всё держалась сверху со второй такой же.
 *
 * Положение считается по прокрутке, а не наблюдателем пересечений:
 * наблюдатель сообщает только моменты пересечения границ, и на короткой
 * странице, где метка попадает в экран сразу, нужный момент он пропускал.
 * Чтение getBoundingClientRect раз в кадр для одного элемента ничего не
 * стоит и ведёт себя одинаково везде.
 *
 * Состояние на уровне модуля, как у замера прохождения: шапка и блок стоят
 * в разных ветках дерева компонентов и через props друг друга не видят.
 */

/** Раскрыта ли панель под прилипшей шапкой. */
const isExpanded = ref(false)

/** Блок сводки показался достаточно — дальше сумму показывает он. */
const isBottomReached = ref(false)

/**
 * Какая часть блока сводки должна попасть в экран, чтобы полоса отпустила
 * сумму. Треть — это заголовок с миниатюрами и первая строка цифр: по ним
 * уже видно, что сводка на месте.
 */
const VISIBLE_RATIO = 0.3

/** Высота полосы: по ней проходит линия передачи. */
const barHeight = ref(52)

export function useSummarySticky() {
  function toggle() {
    isExpanded.value = !isExpanded.value
  }

  /** Полоса сообщает свою высоту — линия передачи проходит по её низу. */
  function setBarHeight(value: number) {
    if (value > 0) {
      barHeight.value = value
    }
  }

  /**
   * Следим за блоком сводки. Возвращает функцию отписки: её вызывает сам
   * блок при размонтировании, иначе слушатели переживут смену версии
   * чекаута.
   */
  function trackSummaryBlock(element: HTMLElement): () => void {
    let frame = 0

    function measure() {
      frame = 0

      const rect = element.getBoundingClientRect()

      // Видимая часть считается от нижнего края полосы, а не от верха
      // экрана: то, что проехало под полосу, человек не видит.
      const top = Math.max(rect.top, barHeight.value)
      const bottom = Math.min(rect.bottom, window.innerHeight)
      const visible = Math.max(0, bottom - top)
      const ratio = rect.height > 0 ? visible / rect.height : 0

      // Второе условие — на случай, когда блок выше оставшейся высоты
      // экрана и доля просто не может дорасти до порога. Тогда полоса
      // отпускает, как только блок дошёл до неё. Нижний край в том же
      // условии отсекает блок, уехавший выше полосы: у него тоже top
      // меньше, но показывать он уже ничего не может.
      //
      // Нулевая высота — это ещё не разложенный блок на первом замере.
      // Без этой проверки он выглядел как блок с top = 0, то есть как
      // доехавший до полосы, и полоса не прилипала до первой прокрутки.
      const reached =
        rect.height > 0 &&
        (ratio >= VISIBLE_RATIO || (rect.top <= barHeight.value && rect.bottom > barHeight.value))

      isBottomReached.value = reached

      if (reached) {
        isExpanded.value = false
      }
    }

    // Пересчёт раз в кадр: событий прокрутки приходит больше, чем экран
    // успевает перерисовать.
    function schedule() {
      if (frame === 0) {
        frame = window.requestAnimationFrame(measure)
      }
    }

    // Первый замер — тоже в кадре: на момент монтирования страница ещё
    // раскладывается, и размеры блока могут быть нулевыми.
    schedule()

    window.addEventListener('scroll', schedule, { passive: true })
    window.addEventListener('resize', schedule)

    return () => {
      window.removeEventListener('scroll', schedule)
      window.removeEventListener('resize', schedule)

      if (frame !== 0) {
        window.cancelAnimationFrame(frame)
      }

      isBottomReached.value = false
    }
  }

  /** Версия чекаута закрылась — состояние не должно протечь в следующую. */
  function resetSticky() {
    isExpanded.value = false
    isBottomReached.value = false
  }

  return {
    isExpanded: computed(() => isExpanded.value),
    /** Полоса прилипшая, пока блок сводки не показался на треть. */
    isSticky: computed(() => !isBottomReached.value),
    toggle,
    setBarHeight,
    trackSummaryBlock,
    resetSticky,
  }
}
